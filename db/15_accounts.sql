-- Accounts waiting for the team (admin approval page)
create or replace view hl_pending_accounts_v as
select u.user_name,
       u.email,
       u.role,
       u.party_name,
       u.status,
       b.buyer_type,
       b.county,
       b.location_name,
       b.contact_phone,
       u.email_verified_at,
       u.created_at
  from hl_app_users u
  left join hl_buyers b on b.buyer_id = u.buyer_id
 where u.status in ('PENDING_EMAIL', 'PENDING_APPROVAL');

