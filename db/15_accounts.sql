create table hl_account_tokens (
  token_hash  varchar2(64)   not null,   -- SHA-256 of the token, hex
  user_name   varchar2(255)  not null,
  purpose     varchar2(10)   not null,
  expires_at  timestamp      not null,
  used_at     timestamp,
  created_at  timestamp      default systimestamp not null,
  constraint hl_account_tokens_pk primary key (token_hash),
  constraint hl_account_tokens_user_fk foreign key (user_name) references hl_app_users on delete cascade,
  constraint hl_account_tokens_purpose_ck check (purpose in ('VERIFY', 'RESET'))
);
create index hl_account_tokens_user_ix on hl_account_tokens (user_name);

create table hl_mail_outbox (
  mail_id     number generated by default on null as identity,
  to_email    varchar2(254)   not null,
  subject     varchar2(200)   not null,
  body_html   clob,                       -- cleared once sent
  body_text   clob,
  status      varchar2(10)    default 'QUEUED' not null,
  attempts    number          default 0 not null,
  last_error  varchar2(1000),
  created_at  timestamp       default systimestamp not null,
  sent_at     timestamp,
  constraint hl_mail_outbox_pk primary key (mail_id),
  constraint hl_mail_outbox_status_ck check (status in ('QUEUED', 'SENT', 'FAILED'))
);

create or replace package hl_mail as

  -- Queues a message and, when MAIL_ENABLED = 1, sends it straight away.
  -- Never raises because of the mail provider: a failed send stays queued
  -- (FAILED after 5 attempts) with LAST_ERROR set.
  function queue (
    p_to       in varchar2,
    p_subject  in varchar2,
    p_html     in clob,
    p_text     in clob) return number;

  -- Sends queued messages (for a scheduler job, or after enabling mail)
  procedure send_pending;

  function is_enabled return boolean;
  function text_setting (p_key in varchar2) return varchar2;

end hl_mail;
/

create or replace package body hl_mail as

  c_api_url    constant varchar2(100) := 'https://api.brevo.com/v3/smtp/email';
  c_credential constant varchar2(30)  := 'BREVO_API';   -- APEX web credential (HTTP header api-key)
  c_max_tries  constant pls_integer   := 5;

  function is_enabled return boolean is
  begin
    return nvl(hl_match_pkg.get_setting('MAIL_ENABLED'), 0) = 1;
  exception
    when others then
      return false;
  end is_enabled;

  function text_setting (p_key in varchar2) return varchar2 is
    l_value hl_text_settings.setting_value%type;
  begin
    select max(setting_value) into l_value from hl_text_settings where setting_key = p_key;
    return l_value;
  end text_setting;

  procedure send_one (p_mail_id in number) is
    l_mail    hl_mail_outbox%rowtype;
    l_body    clob;
    l_reply   clob;
    l_status  number;
    l_error   varchar2(1000);
  begin
    select * into l_mail from hl_mail_outbox where mail_id = p_mail_id for update;
    if l_mail.status <> 'QUEUED' then
      return;
    end if;
    select json_object(
             'sender'      value json_object('name'  value text_setting('MAIL_SENDER_NAME'),
                                             'email' value text_setting('MAIL_SENDER_EMAIL')),
             'to'          value json_array(json_object('email' value l_mail.to_email)),
             'subject'     value l_mail.subject,
             'htmlContent' value l_mail.body_html,
             'textContent' value l_mail.body_text
             returning clob)
      into l_body
      from dual;
    begin
      execute immediate q'[
        begin
          if apex_application.g_flow_id is null then
            apex_util.set_workspace(p_workspace => 'HARVESTLINK');
          end if;
          apex_web_service.clear_request_headers;
          apex_web_service.set_request_headers(
            p_name_01 => 'Content-Type', p_value_01 => 'application/json',
            p_name_02 => 'Accept',       p_value_02 => 'application/json');
          :reply := apex_web_service.make_rest_request(
            p_url                  => :url,
            p_http_method          => 'POST',
            p_body                 => :body,
            p_credential_static_id => :cred);
          :status := apex_web_service.g_status_code;
        end;]'
        using out l_reply, in c_api_url, in l_body, in c_credential, out l_status;
      if l_status not between 200 and 299 then
        l_error := 'HTTP ' || l_status || ': ' || dbms_lob.substr(l_reply, 800, 1);
      end if;
    exception
      when others then
        l_error := substr(sqlerrm, 1, 1000);
    end;

    if l_error is null then
      update hl_mail_outbox
         set status = 'SENT', sent_at = systimestamp, attempts = attempts + 1,
             last_error = null, body_html = null, body_text = null
       where mail_id = p_mail_id;
    else
      update hl_mail_outbox
         set attempts = attempts + 1, last_error = l_error,
             status = case when attempts + 1 >= c_max_tries then 'FAILED' else 'QUEUED' end
       where mail_id = p_mail_id;
    end if;
  end send_one;

  function queue (
    p_to       in varchar2,
    p_subject  in varchar2,
    p_html     in clob,
    p_text     in clob) return number
  is
    l_id hl_mail_outbox.mail_id%type;
  begin
    insert into hl_mail_outbox (to_email, subject, body_html, body_text)
    values (p_to, p_subject, p_html, p_text)
    returning mail_id into l_id;
    if is_enabled then
      send_one(l_id);
    end if;
    return l_id;
  end queue;

  procedure send_pending is
  begin
    if not is_enabled then
      return;
    end if;
    for m in (select mail_id from hl_mail_outbox where status = 'QUEUED' order by mail_id) loop
      send_one(m.mail_id);
      commit;
    end loop;
  end send_pending;

end hl_mail;
