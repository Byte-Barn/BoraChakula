create or replace package body hl_account_api as

  c_iterations   constant pls_integer := 10000;
  c_max_failures constant pls_integer := 5;
  c_lock_minutes constant pls_integer := 15;

  g_status varchar2(20);
  g_user   varchar2(255);

  -- PBKDF2-HMAC-SHA256, one 32-byte block
  function pbkdf2 (p_password in varchar2, p_salt in raw, p_iterations in pls_integer) return raw is
    l_key raw(2000) := utl_i18n.string_to_raw(p_password, 'AL32UTF8');
    l_u   raw(32);
    l_t   raw(32);
  begin
    l_u := dbms_crypto.mac(utl_raw.concat(p_salt, hextoraw('00000001')), dbms_crypto.hmac_sh256, l_key);
    l_t := l_u;
    for i in 2 .. p_iterations loop
      l_u := dbms_crypto.mac(l_u, dbms_crypto.hmac_sh256, l_key);
      l_t := utl_raw.bit_xor(l_t, l_u);
    end loop;
    return l_t;
  end pbkdf2;

  function hash_password (p_password in varchar2) return varchar2 is
    l_salt raw(16) := dbms_crypto.randombytes(16);
  begin
    return 'pbkdf2-sha256$' || c_iterations || '$' || rawtohex(l_salt) || '$'
        || rawtohex(pbkdf2(p_password, l_salt, c_iterations));
  end hash_password;

  function password_matches (p_password in varchar2, p_stored in varchar2) return boolean is
    l_iter pls_integer;
    l_salt raw(16);
    l_hash varchar2(64);
    l_calc varchar2(64);
    l_diff pls_integer := 0;
  begin
    if p_stored is null or regexp_count(p_stored, '\$') <> 3 then
      return false;
    end if;
    l_iter := to_number(regexp_substr(p_stored, '[^$]+', 1, 2));
    l_salt := hextoraw(regexp_substr(p_stored, '[^$]+', 1, 3));
    l_hash := regexp_substr(p_stored, '[^$]+', 1, 4);
    l_calc := rawtohex(pbkdf2(p_password, l_salt, l_iter));
    -- Compare every character, so the time doesn't depend on where they differ
    for i in 1 .. greatest(length(l_hash), length(l_calc)) loop
      if nvl(substr(l_hash, i, 1), '-') <> nvl(substr(l_calc, i, 1), '+') then
        l_diff := l_diff + 1;
      end if;
    end loop;
    return l_diff = 0;
  end password_matches;

  function password_problem (p_password in varchar2) return varchar2 is
  begin
    if p_password is null or length(p_password) < 10 then
      return 'Use at least 10 characters.';
    elsif length(p_password) > 128 then
      return 'Use at most 128 characters.';
    elsif regexp_like(p_password, '^[0-9]+$') then
      return 'Use letters as well as numbers.';
    end if;
    return null;
  end password_problem;

  procedure check_password (p_password in varchar2) is
    l_problem varchar2(100) := password_problem(p_password);
  begin
    if l_problem is not null then
      raise_application_error(-20704, 'Password too weak. ' || l_problem);
    end if;
  end check_password;

  function account (p_user_name in varchar2) return hl_app_users%rowtype is
    l_row hl_app_users%rowtype;
  begin
    select * into l_row from hl_app_users where user_name = upper(p_user_name);
    return l_row;
  exception
    when no_data_found then
      return null;
  end account;

  function find_login (p_login in varchar2) return hl_app_users%rowtype is
    l_row hl_app_users%rowtype;
  begin
    select * into l_row
      from hl_app_users
     where lower(email) = lower(trim(p_login)) or user_name = upper(trim(p_login))
     fetch first 1 row only;
    return l_row;
  exception
    when no_data_found then
      return null;
  end find_login;

  -- New one-time token for a user; returns the token itself (only its hash is kept)
  function new_token (p_user_name in varchar2, p_purpose in varchar2, p_valid_hours in number) return varchar2 is
    l_token varchar2(64) := lower(rawtohex(dbms_crypto.randombytes(32)));
  begin
    -- An unused token of the same purpose is replaced by the new one
    delete from hl_account_tokens where user_name = p_user_name and purpose = p_purpose and used_at is null;
    insert into hl_account_tokens (token_hash, user_name, purpose, expires_at)
    values (lower(rawtohex(dbms_crypto.hash(utl_i18n.string_to_raw(l_token, 'AL32UTF8'), dbms_crypto.hash_sh256))),
            p_user_name, p_purpose, systimestamp + numtodsinterval(p_valid_hours, 'HOUR'));
    return l_token;
  end new_token;

  -- The account a valid, unused token belongs to; marks the token used
  function use_token (p_token in varchar2, p_purpose in varchar2) return varchar2 is
    l_user hl_account_tokens.user_name%type;
    l_hash varchar2(64);
  begin
    if p_token is null or not regexp_like(p_token, '^[0-9a-fA-F]{64}$') then
      raise_application_error(-20708, 'This link is not valid or has expired. Ask for a new one.');
    end if;
    l_hash := lower(rawtohex(dbms_crypto.hash(utl_i18n.string_to_raw(lower(p_token), 'AL32UTF8'), dbms_crypto.hash_sh256)));
    update hl_account_tokens
       set used_at = systimestamp
     where token_hash = l_hash and purpose = p_purpose and used_at is null and expires_at > systimestamp
    returning user_name into l_user;
    if l_user is null then
      raise_application_error(-20708, 'This link is not valid or has expired. Ask for a new one.');
    end if;
    return l_user;
  end use_token;

  function link (p_setting in varchar2, p_token in varchar2) return varchar2 is
  begin
    return replace(hl_mail.text_setting(p_setting), '#TOKEN#', p_token);
  end link;

  function esc (p_text in varchar2) return varchar2 is
  begin
    return replace(replace(replace(replace(p_text, '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;');
  end esc;

  -- One email layout: greeting, one paragraph, an optional button, a footer
  procedure send (p_to in varchar2, p_name in varchar2, p_subject in varchar2,
                  p_paragraph in varchar2, p_button in varchar2 default null, p_url in varchar2 default null) is
    l_id number;
  begin
    l_id := hl_mail.queue(
      p_to      => p_to,
      p_subject => p_subject,
      p_html    => '<div style="font-family:Arial,sans-serif;font-size:15px;line-height:22px;color:#1f2a24;max-width:520px">'
                || '<p>Habari ' || esc(p_name) || ',</p><p>' || esc(p_paragraph) || '</p>'
                || case when p_url is not null then
                     '<p><a href="' || esc(p_url) || '" style="display:inline-block;background:#1f6b3a;color:#ffffff;'
                     || 'padding:12px 20px;border-radius:10px;text-decoration:none;font-weight:bold">' || esc(p_button) || '</a></p>'
                     || '<p style="font-size:13px;color:#5b6b61">Or open this link: ' || esc(p_url) || '</p>' end
                || '<p style="font-size:13px;color:#5b6b61">HarvestLink by Bora Chakula. If you did not ask for this, ignore this email.</p></div>',
      p_text    => 'Habari ' || p_name || ',' || chr(10) || chr(10) || p_paragraph
                || case when p_url is not null then chr(10) || chr(10) || p_button || ': ' || p_url end
                || chr(10) || chr(10) || 'HarvestLink by Bora Chakula. If you did not ask for this, ignore this email.');
  end send;

  procedure send_verification (p_user in hl_app_users%rowtype) is
  begin
    send(p_user.email, p_user.party_name, 'Confirm your HarvestLink email',
         'Confirm your email address to finish signing up. The link works for 24 hours.',
         'Confirm my email', link('VERIFY_URL', new_token(p_user.user_name, 'VERIFY', 24)));
  end send_verification;

  function register (
    p_email         in varchar2,
    p_password      in varchar2,
    p_role          in varchar2,
    p_name          in varchar2,
    p_phone         in varchar2,
    p_county        in varchar2,
    p_location_name in varchar2,
    p_latitude      in number,
    p_longitude     in number,
    p_buyer_type    in varchar2 default null,
    p_consent       in varchar2 default 'N') return varchar2
  is
    l_role   varchar2(10)  := upper(trim(p_role));
    l_email  varchar2(254) := lower(trim(p_email));
    l_name   varchar2(150) := trim(p_name);
    l_count  number;
    l_party  number;
    l_user   hl_app_users%rowtype;
    l_hash   varchar2(200);
  begin
    if l_role is null or l_role not in ('FARMER', 'BUYER') then
      raise_application_error(-20701, 'Sign up as a farmer or a buyer');
    end if;
    if l_email is null or length(l_email) > 254
       or not regexp_like(l_email, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
      raise_application_error(-20702, 'Enter a valid email address');
    end if;
    select count(*) into l_count from hl_app_users where lower(email) = l_email or user_name = upper(l_email);
    if l_count > 0 then
      raise_application_error(-20703, 'An account with this email already exists. Sign in or reset your password.');
    end if;
    check_password(p_password);
    if l_name is null then
      raise_application_error(-20705, case l_role when 'FARMER' then 'Enter your full name' else 'Enter your business name' end);
    end if;
    if p_county is null or p_latitude is null or p_longitude is null
       or p_latitude not between -5 and 5.5 or p_longitude not between 33.5 and 42 then
      raise_application_error(-20706, 'Choose your location in Kenya');
    end if;

    if l_role = 'FARMER' then
      if nvl(upper(p_consent), 'N') <> 'Y' then
        raise_application_error(-20707, 'Agree to the data notice to sign up as a farmer');
      end if;
      if p_phone is null then
        raise_application_error(-20709, 'Enter your phone number');
      end if;
      select count(*) into l_count from hl_farmers where phone = trim(p_phone);
      if l_count > 0 then
        raise_application_error(-20709, 'A farmer with this phone number is already registered');
      end if;
      insert into hl_farmers (full_name, phone, county, location_name, latitude, longitude, consent_given)
      values (l_name, trim(p_phone), p_county, p_location_name, p_latitude, p_longitude, 'Y')
      returning farmer_id into l_party;
    else
      if p_buyer_type is null or upper(p_buyer_type) not in
         ('RETAILER', 'EXPORTER', 'PROCESSOR', 'SCHOOL', 'HOTEL', 'WHOLESALE_MARKET') then
        raise_application_error(-20710, 'Choose what kind of buyer you are');
      end if;
      insert into hl_buyers (buyer_name, buyer_type, contact_phone, contact_email, county, location_name,
                             latitude, longitude)
      values (l_name, upper(p_buyer_type), trim(p_phone), l_email, p_county, p_location_name,
              p_latitude, p_longitude)
      returning buyer_id into l_party;
    end if;

    l_hash := hash_password(p_password);
    insert into hl_app_users (user_name, role, party_name, farmer_id, buyer_id, email, password_hash, status)
    values (upper(l_email), l_role, l_name,
            case l_role when 'FARMER' then l_party end, case l_role when 'BUYER' then l_party end,
            l_email, l_hash, 'PENDING_EMAIL');

    l_user := account(l_email);
    send_verification(l_user);
    return l_user.user_name;
  end register;

  function verify_email (p_token in varchar2) return varchar2 is
    l_user hl_app_users%rowtype := account(use_token(p_token, 'VERIFY'));
    l_new  varchar2(20);
  begin
    if l_user.status = 'PENDING_EMAIL' then
      l_new := case l_user.role when 'BUYER' then 'PENDING_APPROVAL' else 'ACTIVE' end;
      update hl_app_users set status = l_new, email_verified_at = systimestamp
       where user_name = l_user.user_name;
      if l_new = 'PENDING_APPROVAL' then
        send(l_user.email, l_user.party_name, 'We are reviewing your HarvestLink buyer account',
             'Thank you for confirming your email. Our team checks every buyer before their first order; '
             || 'we will email you as soon as your account is approved.');
      end if;
      return l_new;
    end if;
    return l_user.status;
  end verify_email;

  procedure resend_verification (p_email in varchar2) is
    l_user hl_app_users%rowtype := find_login(p_email);
  begin
    if l_user.status = 'PENDING_EMAIL' and l_user.email is not null then
      send_verification(l_user);
    end if;
  end resend_verification;

  procedure request_password_reset (p_email in varchar2) is
    l_user hl_app_users%rowtype := find_login(p_email);
  begin
    if l_user.email is not null and l_user.status <> 'DISABLED' then
      send(l_user.email, nvl(l_user.party_name, 'there'), 'Reset your HarvestLink password',
           'Someone asked to reset the password for this email address. The link works for 1 hour.',
           'Choose a new password', link('RESET_URL', new_token(l_user.user_name, 'RESET', 1)));
    end if;
  end request_password_reset;

  procedure reset_password (p_token in varchar2, p_new_password in varchar2) is
    l_user varchar2(255);
    l_hash varchar2(200);
  begin
    check_password(p_new_password);
    l_user := use_token(p_token, 'RESET');
    l_hash := hash_password(p_new_password);
    update hl_app_users
       set password_hash = l_hash, failed_logins = 0, locked_until = null,
           -- the reset link proves the email address too
           email_verified_at = nvl(email_verified_at, systimestamp),
           status = case when status = 'PENDING_EMAIL'
                         then case role when 'BUYER' then 'PENDING_APPROVAL' else 'ACTIVE' end
                         else status end
     where user_name = l_user;
    delete from hl_account_tokens where user_name = l_user and purpose = 'RESET' and used_at is null;
  end reset_password;

  procedure change_password (p_current_password in varchar2, p_new_password in varchar2) is
    l_user hl_app_users%rowtype := account(hl_auth.app_user);
  begin
    if l_user.user_name is null or not password_matches(p_current_password, l_user.password_hash) then
      raise_application_error(-20711, 'Your current password is not right');
    end if;
    check_password(p_new_password);
    l_user.password_hash := hash_password(p_new_password);
    update hl_app_users set password_hash = l_user.password_hash where user_name = l_user.user_name;
  end change_password;

  procedure require_ops is
  begin
    if not hl_auth.is_ops then
      raise_application_error(-20712, 'Only the HarvestLink team can do this');
    end if;
  end require_ops;

  procedure approve (p_user_name in varchar2) is
    l_user hl_app_users%rowtype := account(p_user_name);
  begin
    require_ops;
    if l_user.status <> 'PENDING_APPROVAL' or l_user.status is null then
      raise_application_error(-20712, 'This account is not waiting for approval');
    end if;
    update hl_app_users
       set status = 'ACTIVE', approved_at = systimestamp, approved_by = hl_auth.app_user
     where user_name = l_user.user_name;
    send(l_user.email, l_user.party_name, 'Your HarvestLink buyer account is approved',
         'Your account is ready. Sign in to post your first demand; we will match it with farmers before harvest.',
         'Sign in', hl_mail.text_setting('SIGN_IN_URL'));
  end approve;

  procedure set_disabled (p_user_name in varchar2, p_disabled in boolean) is
    l_user hl_app_users%rowtype := account(p_user_name);
  begin
    require_ops;
    if l_user.user_name is null then
      raise_application_error(-20712, 'No such account');
    elsif l_user.user_name = hl_auth.app_user then
      raise_application_error(-20712, 'You cannot disable your own account');
    end if;
    update hl_app_users
       set status = case when p_disabled then 'DISABLED'
                         when email_verified_at is null and email is not null then 'PENDING_EMAIL'
                         when role = 'BUYER' and approved_at is null and email is not null then 'PENDING_APPROVAL'
                         else 'ACTIVE' end
     where user_name = l_user.user_name;
  end set_disabled;

  procedure set_password (p_user_name in varchar2, p_password in varchar2) is
    l_hash varchar2(200);
  begin
    check_password(p_password);
    l_hash := hash_password(p_password);
    update hl_app_users
       set password_hash = l_hash, status = 'ACTIVE', failed_logins = 0, locked_until = null
     where user_name = upper(p_user_name);
    if sql%rowcount = 0 then
      raise_application_error(-20712, 'No such account: ' || p_user_name);
    end if;
  end set_password;

  -- Login bookkeeping commits on its own, whatever happens to the page's transaction
  procedure record_attempt (p_user_name in varchar2, p_success in boolean) is
    pragma autonomous_transaction;
  begin
    if p_success then
      update hl_app_users
         set failed_logins = 0, locked_until = null, last_login_at = systimestamp
       where user_name = p_user_name;
    else
      update hl_app_users
         set failed_logins = failed_logins + 1,
             locked_until = case when failed_logins + 1 >= c_max_failures
                                 then systimestamp + numtodsinterval(c_lock_minutes, 'MINUTE') end
       where user_name = p_user_name;
    end if;
    commit;
  end record_attempt;

  function authenticate (p_username in varchar2, p_password in varchar2) return boolean is
    l_user hl_app_users%rowtype := find_login(p_username);
    l_ok   boolean;
  begin
    g_user := null;
    if l_user.user_name is null then
      -- Same work as a real check, so timing doesn't reveal which emails exist
      l_ok := password_matches(p_password, 'pbkdf2-sha256$' || c_iterations || '$00000000000000000000000000000000$00');
      g_status := 'INVALID';
      return false;
    end if;
    if l_user.locked_until > systimestamp then
      g_status := 'LOCKED';
      return false;
    end if;
    l_ok := password_matches(p_password, l_user.password_hash);
    record_attempt(l_user.user_name, l_ok);
    if not l_ok then
      g_status := 'INVALID';
      return false;
    end if;
    if l_user.status <> 'ACTIVE' then
      g_status := l_user.status;
      return false;
    end if;
    g_status := 'OK';
    g_user   := l_user.user_name;
    return true;
  end authenticate;

  function login_status return varchar2 is
  begin
    return g_status;
  end login_status;

  function login_user return varchar2 is
  begin
    return g_user;
  end login_user;

  function login_message return varchar2 is
  begin
    return case g_status
      when 'LOCKED'           then 'Too many wrong passwords. Try again in ' || c_lock_minutes || ' minutes, or reset your password.'
      when 'PENDING_EMAIL'    then 'Confirm your email first: open the link we sent you, or ask for a new one.'
      when 'PENDING_APPROVAL' then 'Your buyer account is waiting for approval. We will email you when it is ready.'
      when 'DISABLED'         then 'This account is disabled. Contact the HarvestLink team.'
      when 'INVALID'          then 'Email or password is not right.'
    end;
  end login_message;

end hl_account_api;
