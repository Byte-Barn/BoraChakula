create or replace package hl_account_api as

  -- Sign-up for farmers and buyers. Creates the farmer or buyer record and a
  -- PENDING_EMAIL account named after the email, and emails a verification
  -- link (valid 24 hours). Returns the user name. Farmers must give consent
  -- (p_consent = 'Y') and a phone number; buyers a buyer type.
  -- Latitude and longitude place the party for matching.
  function register (
    p_email         in varchar2,
    p_password      in varchar2,
    p_role          in varchar2,
    p_name          in varchar2,
    p_phone         in varchar2,
    p_county        in varchar2,
    p_location_name in varchar2,
    p_latitude      in number,
    p_longitude     in number,
    p_buyer_type    in varchar2 default null,
    p_consent       in varchar2 default 'N') return varchar2;

  -- Confirms the email. Returns the new status: ACTIVE (farmer) or
  -- PENDING_APPROVAL (buyer, emailed when approved).
  function verify_email (p_token in varchar2) return varchar2;

  -- Sends a new verification link. Says nothing about unknown addresses.
  procedure resend_verification (p_email in varchar2);

  -- Emails a reset link (valid 1 hour). Says nothing about unknown addresses.
  procedure request_password_reset (p_email in varchar2);

  -- Sets a new password from a reset link, and unlocks the account.
  procedure reset_password (p_token in varchar2, p_new_password in varchar2);

  -- The signed-in user changes their password.
  procedure change_password (p_current_password in varchar2, p_new_password in varchar2);

  -- Admin (OPS) only: activate a buyer awaiting approval, or disable /
  -- re-enable an account.
  procedure approve (p_user_name in varchar2);
  procedure set_disabled (p_user_name in varchar2, p_disabled in boolean);

  -- Setup scripts only (demo and admin logins): sets a password and makes the
  -- account ACTIVE. Not for pages.
  procedure set_password (p_user_name in varchar2, p_password in varchar2);

  -- Custom APEX authentication function. Accepts the email or the user name.
  -- True only for an ACTIVE account with the right password.
  function authenticate (p_username in varchar2, p_password in varchar2) return boolean;

  -- After authenticate: why it failed (INVALID, LOCKED, PENDING_EMAIL,
  -- PENDING_APPROVAL, DISABLED) or OK, the user name to sign in as, and a
  -- message for the login page.
  function login_status return varchar2;
  function login_user return varchar2;
  function login_message return varchar2;

  -- Password rules, for page validation messages
  function password_problem (p_password in varchar2) return varchar2;

end hl_account_api;
