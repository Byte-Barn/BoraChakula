-- HarvestLink: sign-up, sign-in, email verification and password reset.
--
-- Accounts are rows of HL_APP_USERS (db/09_auth.sql). Farmers and buyers sign
-- up themselves; operations (admin) accounts are created by scripts.
--   farmer: PENDING_EMAIL -> verify email -> ACTIVE
--   buyer:  PENDING_EMAIL -> verify email -> PENDING_APPROVAL -> admin approves -> ACTIVE
-- Only ACTIVE accounts can sign in. The APEX app authenticates with
-- HL_ACCOUNT_API.AUTHENTICATE (a custom authentication scheme).
--
-- Passwords: PBKDF2-HMAC-SHA256 with a random 16-byte salt, stored as
-- pbkdf2-sha256$<iterations>$<salt hex>$<hash hex>. Five wrong passwords lock
-- the account for 15 minutes. Verification and reset tokens are random 32-byte
-- values; only their SHA-256 hash is stored, and each can be used once.
--
-- Email goes through HL_MAIL: messages are queued in HL_MAIL_OUTBOX and sent
-- with Brevo's transactional email API when MAIL_ENABLED = 1 (set up by
-- scripts/enable_brevo.py). Otherwise they stay queued, so sign-up works and
-- tests run without email. A sent message's body is cleared, since it can
-- carry a one-time link.
--
-- Needs EXECUTE on DBMS_CRYPTO (scripts/bootstrap_db.py and db/tests/run.sh
-- grant it). APEX_WEB_SERVICE is called through dynamic SQL, so this file
-- installs on databases without APEX.
--
-- Error codes: -20701..-20712 (docs/backend-api.md).

merge into hl_settings s
using (select 'MAIL_ENABLED' as setting_key, 0 as setting_value,
              'Send account emails with Brevo: 1 = on, 0 = queue only (HL_MAIL_OUTBOX)' as description
         from dual) n
   on (s.setting_key = n.setting_key)
 when not matched then insert (setting_key, setting_value, description)
                       values (n.setting_key, n.setting_value, n.description);

-- Text settings for email: sender, and the page links with a #TOKEN# placeholder
