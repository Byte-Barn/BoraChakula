-- HarvestLink: crop prices from the team's market interviews.
--
-- Each answer to "Broker price vs market price" on the interview record form
-- (Appendix A of docs/HarvestLink_Hackathon_Plan.pdf) becomes one row in
-- HL_PRICE_OBSERVATIONS: no names, only the market, date, the interviewee's
-- role and the prices in KES per kg. HL_PRICE_SUMMARY_V shows the medians
-- beside the current prices; hl_calibration.apply_interview_prices then sets
-- each crop's price to the median of its observations and records the source,
-- which flows into the income uplift method and provenance
-- (HL_IMPACT_METRICS_V). Steps: docs/operations.md, "Market interview prices".
--
-- Error codes: -20621..-20629 (docs/backend-api.md).

create table hl_price_observations (
  observation_id   number generated by default on null as identity,
  observed_on      date           not null,
  market           varchar2(100)  not null,   -- e.g. Murang'a town market
  interviewee_role varchar2(10)   not null,
  crop_name        varchar2(100)  not null,
  broker_price_kg  number(10,2),              -- what brokers pay the farmer at the farm gate
  market_price_kg  number(10,2),              -- wholesale price at the market
  quoted_as        varchar2(100),             -- the answer as given, e.g. 'KES 2,500 per 64 kg crate'
  notes            varchar2(400),
  entered_by       varchar2(255)  default coalesce(sys_context('APEX$SESSION', 'APP_USER'),
                                                   sys_context('USERENV', 'SESSION_USER')) not null,
  created_at       timestamp      default systimestamp not null,
  constraint hl_price_obs_pk primary key (observation_id),
  constraint hl_price_obs_crop_fk foreign key (crop_name) references hl_crops (crop_name),
  constraint hl_price_obs_role_ck check (interviewee_role in ('FARMER', 'TRADER', 'BROKER', 'OTHER')),
  constraint hl_price_obs_price_ck check (broker_price_kg is not null or market_price_kg is not null),
  constraint hl_price_obs_positive_ck check (nvl(broker_price_kg, 1) > 0 and nvl(market_price_kg, 1) > 0)
);

-- Per crop: observations, medians and range, beside the price in use and its source
create or replace view hl_price_summary_v as
select c.crop_id,
       c.crop_name,
       count(o.broker_price_kg)              as broker_observations,
       median(o.broker_price_kg)             as broker_median_kg,
       min(o.broker_price_kg)                as broker_min_kg,
       max(o.broker_price_kg)                as broker_max_kg,
       c.typical_broker_price_kg             as broker_price_in_use,
       c.broker_price_basis,
       c.broker_price_source,
       count(o.market_price_kg)              as market_observations,
       median(o.market_price_kg)             as market_median_kg,
       min(o.market_price_kg)                as market_min_kg,
       max(o.market_price_kg)                as market_max_kg,
       c.typical_market_price_kg             as market_price_in_use,
       c.market_price_basis,
       c.market_price_source
  from hl_crops c
  left join hl_price_observations o on o.crop_name = c.crop_name
 group by c.crop_id, c.crop_name, c.typical_broker_price_kg, c.broker_price_basis, c.broker_price_source,
          c.typical_market_price_kg, c.market_price_basis, c.market_price_source;

create or replace package hl_calibration as

  -- Operations only. For every crop with at least p_min_observations broker
  -- (or market) prices, sets that price to the median of the observations,
  -- with basis INTERVIEW and a source such as
  -- "Market interviews, Murang'a town market, 15 Oct 2026: median of 6".
  -- Crops with fewer observations keep their price. Returns the number of
  -- prices changed. Commits nothing.
  function apply_interview_prices (p_min_observations in pls_integer default 3) return pls_integer;

end hl_calibration;
/

create or replace package body hl_calibration as

  function source_text (p_crop in varchar2, p_which in varchar2, p_n in pls_integer) return varchar2 is
    l_markets varchar2(4000);
    l_from    date;
    l_to      date;
  begin
    select listagg(distinct market, ', ') within group (order by market), min(observed_on), max(observed_on)
      into l_markets, l_from, l_to
      from hl_price_observations
     where crop_name = p_crop
       and ((p_which = 'BROKER' and broker_price_kg is not null)
         or (p_which = 'MARKET' and market_price_kg is not null));
    return substr('Market interviews, ' || l_markets || ', ' || to_char(l_from, 'DD Mon YYYY')
                  || case when l_to > l_from then '–' || to_char(l_to, 'DD Mon YYYY') end
                  || ': median of ' || p_n, 1, 300);
  end source_text;

  function apply_interview_prices (p_min_observations in pls_integer default 3) return pls_integer is
    l_changed pls_integer := 0;
    l_source  hl_crops.broker_price_source%type;
  begin
    if not hl_auth.is_ops
       and not (hl_auth.role is null and sys_context('APEX$SESSION', 'APP_USER') is null) then
      raise_application_error(-20621, 'Only operations can change crop prices');
    end if;
    if p_min_observations is null or p_min_observations < 1 then
      raise_application_error(-20622, 'Minimum number of observations must be at least 1');
    end if;

    for s in (select * from hl_price_summary_v) loop
      if s.broker_observations >= p_min_observations then
        l_source := source_text(s.crop_name, 'BROKER', s.broker_observations);
        update hl_crops
           set typical_broker_price_kg = round(s.broker_median_kg, 2),
               broker_price_basis      = 'INTERVIEW',
               broker_price_source     = l_source
         where crop_id = s.crop_id;
        l_changed := l_changed + 1;
      end if;
      if s.market_observations >= p_min_observations then
        l_source := source_text(s.crop_name, 'MARKET', s.market_observations);
        update hl_crops
           set typical_market_price_kg = round(s.market_median_kg, 2),
               market_price_basis      = 'INTERVIEW',
               market_price_source     = l_source
         where crop_id = s.crop_id;
        l_changed := l_changed + 1;
      end if;
    end loop;
    return l_changed;
  end apply_interview_prices;

end hl_calibration;
/
