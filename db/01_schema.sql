-- =============================================================================
-- HarvestLink schema (Oracle Autonomous Database / Oracle Database 23ai)
-- Demand-first agricultural marketplace: buyers post needs before harvest,
-- farmers register expected harvests, the matching engine aggregates farmers
-- into orders, routes produce by grade and plans shared pickups.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Tunable parameters used by the matching engine and impact calculations
-- ---------------------------------------------------------------------------
create table hl_settings (
  setting_key    varchar2(50)  not null,
  setting_value  number        not null,
  description    varchar2(400),
  constraint hl_settings_pk primary key (setting_key)
);

-- ---------------------------------------------------------------------------
-- Reference data
-- ---------------------------------------------------------------------------
create table hl_crops (
  crop_id                 number generated by default on null as identity,
  crop_name               varchar2(100) not null,
  shelf_life_days         number(4)     not null,
  typical_broker_price_kg number(10,2),   -- KES/kg paid by middlemen at farm gate
  typical_market_price_kg number(10,2),   -- KES/kg at wholesale market
  constraint hl_crops_pk primary key (crop_id),
  constraint hl_crops_name_uk unique (crop_name),
  constraint hl_crops_shelf_ck check (shelf_life_days > 0)
);

-- ---------------------------------------------------------------------------
-- Participants
-- ---------------------------------------------------------------------------
create table hl_farmers (
  farmer_id       number generated by default on null as identity,
  full_name       varchar2(150) not null,
  phone           varchar2(20)  not null,
  county          varchar2(60)  not null,
  location_name   varchar2(100),
  latitude        number(9,6)   not null,
  longitude       number(9,6)   not null,
  cooperative     varchar2(150),
  has_smartphone  varchar2(1)   default 'N' not null,
  consent_given   varchar2(1)   default 'N' not null,
  created_at      timestamp     default systimestamp not null,
  constraint hl_farmers_pk primary key (farmer_id),
  constraint hl_farmers_phone_uk unique (phone),
  constraint hl_farmers_smart_ck check (has_smartphone in ('Y','N')),
  constraint hl_farmers_consent_ck check (consent_given in ('Y','N'))
);

create table hl_buyers (
  buyer_id         number generated by default on null as identity,
  buyer_name       varchar2(150) not null,
  buyer_type       varchar2(20)  not null,
  contact_phone    varchar2(20),
  contact_email    varchar2(150),
  county           varchar2(60)  not null,
  location_name    varchar2(100),
  latitude         number(9,6)   not null,
  longitude        number(9,6)   not null,
  accepted_grades  varchar2(10)  default 'A' not null,  -- e.g. 'A', 'A,B', 'B,C'
  kra_pin          varchar2(20),
  is_verified      varchar2(1)   default 'N' not null,
  created_at       timestamp     default systimestamp not null,
  constraint hl_buyers_pk primary key (buyer_id),
  constraint hl_buyers_type_ck check (buyer_type in
    ('RETAILER','EXPORTER','PROCESSOR','SCHOOL','HOTEL','WHOLESALE_MARKET')),
  constraint hl_buyers_verified_ck check (is_verified in ('Y','N'))
);

-- ---------------------------------------------------------------------------
-- Supply: expected harvests registered by farmers before harvest
-- ---------------------------------------------------------------------------
create table hl_harvests (
  harvest_id      number generated by default on null as identity,
  farmer_id       number        not null,
  crop_id         number        not null,
  grade           varchar2(1)   not null,
  expected_qty_kg number(10,2)  not null,
  harvest_from    date          not null,
  harvest_to      date          not null,
  status          varchar2(20)  default 'OPEN' not null,
  notes           varchar2(400),
  created_at      timestamp     default systimestamp not null,
  constraint hl_harvests_pk primary key (harvest_id),
  constraint hl_harvests_farmer_fk foreign key (farmer_id) references hl_farmers,
  constraint hl_harvests_crop_fk foreign key (crop_id) references hl_crops,
  constraint hl_harvests_grade_ck check (grade in ('A','B','C')),
  constraint hl_harvests_qty_ck check (expected_qty_kg > 0),
  constraint hl_harvests_dates_ck check (harvest_to >= harvest_from),
  constraint hl_harvests_status_ck check (status in
    ('OPEN','PARTIAL','COMMITTED','HARVESTED','CANCELLED'))
);
create index hl_harvests_crop_ix on hl_harvests (crop_id, status);
create index hl_harvests_farmer_ix on hl_harvests (farmer_id);

-- ---------------------------------------------------------------------------
-- Demand: produce needs posted by buyers ahead of harvest
-- ---------------------------------------------------------------------------
create table hl_demands (
  demand_id        number generated by default on null as identity,
  buyer_id         number        not null,
  crop_id          number        not null,
  grade_required   varchar2(1)   not null,   -- minimum acceptable grade
  quantity_kg      number(10,2)  not null,
  price_per_kg     number(10,2)  not null,   -- KES/kg offered by the buyer
  need_by_date     date          not null,
  delivery_lat     number(9,6),              -- defaults to buyer location
  delivery_lon     number(9,6),
  status           varchar2(20)  default 'OPEN' not null,
  notes            varchar2(400),
  created_at       timestamp     default systimestamp not null,
  constraint hl_demands_pk primary key (demand_id),
  constraint hl_demands_buyer_fk foreign key (buyer_id) references hl_buyers,
  constraint hl_demands_crop_fk foreign key (crop_id) references hl_crops,
  constraint hl_demands_grade_ck check (grade_required in ('A','B','C')),
  constraint hl_demands_qty_ck check (quantity_kg > 0),
  constraint hl_demands_price_ck check (price_per_kg > 0),
  constraint hl_demands_status_ck check (status in
    ('OPEN','PARTIAL','FILLED','CLOSED','CANCELLED'))
);
create index hl_demands_crop_ix on hl_demands (crop_id, status);
create index hl_demands_buyer_ix on hl_demands (buyer_id);

-- ---------------------------------------------------------------------------
-- Logistics: one aggregated pickup route per demand
-- ---------------------------------------------------------------------------
create table hl_routes (
  route_id          number generated by default on null as identity,
  demand_id         number        not null,
  total_qty_kg      number(10,2)  not null,
  stops             number(4)     not null,
  vehicle_type      varchar2(10)  not null,  -- TRUCK/PICKUP shared route, or DIRECT
  trips             number(4)     not null,
  aggregated_km     number(10,2)  not null,  -- shared route(s)
  individual_km     number(10,2)  not null,  -- baseline: each farmer travels alone
  aggregated_co2_kg number(10,2)  not null,
  individual_co2_kg number(10,2)  not null,
  route_sequence    varchar2(4000),          -- ordered farmer stop list
  status            varchar2(20)  default 'PLANNED' not null,
  created_at        timestamp     default systimestamp not null,
  constraint hl_routes_pk primary key (route_id),
  constraint hl_routes_demand_fk foreign key (demand_id) references hl_demands on delete cascade,
  constraint hl_routes_demand_uk unique (demand_id),
  constraint hl_routes_vehicle_ck check (vehicle_type in ('TRUCK','PICKUP','DIRECT')),
  constraint hl_routes_status_ck check (status in
    ('PLANNED','DISPATCHED','COMPLETED','CANCELLED'))
);

-- ---------------------------------------------------------------------------
-- Matches: allocation of harvest volume to a demand, with explainable scores
-- ---------------------------------------------------------------------------
create table hl_matches (
  match_id        number generated by default on null as identity,
  demand_id       number        not null,
  harvest_id      number        not null,
  allocated_kg    number(10,2)  not null,
  distance_km     number(8,2)   not null,
  score_total     number(5,4)   not null,
  score_quantity  number(5,4)   not null,
  score_grade     number(5,4)   not null,
  score_timing    number(5,4)   not null,
  score_distance  number(5,4)   not null,
  match_reason    varchar2(1000),
  stop_order      number(4),
  status          varchar2(20)  default 'PROPOSED' not null,
  created_at      timestamp     default systimestamp not null,
  constraint hl_matches_pk primary key (match_id),
  constraint hl_matches_demand_fk foreign key (demand_id) references hl_demands on delete cascade,
  constraint hl_matches_harvest_fk foreign key (harvest_id) references hl_harvests on delete cascade,
  constraint hl_matches_uk unique (demand_id, harvest_id),
  constraint hl_matches_qty_ck check (allocated_kg > 0),
  constraint hl_matches_status_ck check (status in
    ('PROPOSED','ACCEPTED','REJECTED','DELIVERED'))
);
create index hl_matches_harvest_ix on hl_matches (harvest_id);
