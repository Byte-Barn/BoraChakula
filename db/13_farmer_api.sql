-- HarvestLink: farmer data rights (Kenya Data Protection Act, 2019).
--
-- HL_FARMER_API lets a farmer (or operations, on their behalf) record consent,
-- get a copy of everything held about them, and delete their account.
--
-- What deletion does and does not remove (docs/architecture.md, section 7):
--   * The farmer row, their harvests, open offers (PROPOSED matches), grade
--     allocations, pickup stops and their APP_USER login mapping are deleted,
--     so they disappear from every view and from matching.
--   * Confirmed (ACCEPTED) matches are declined first, so the ledger records
--     that the agreement ended. Those new ledger rows carry a pseudonym
--     ("Erased farmer #n") and a placeholder phone, never the real details.
--   * Delivered matches are deleted with the harvest; buyers keep the order
--     totals but no longer see who supplied it.
--   * HL_AGREEMENTS rows written before the deletion still hold the real name
--     and phone. It is a blockchain table: rows cannot be updated, and cannot
--     be deleted until 16 days after insert. HL_ERASURES records when that
--     window ends (PURGE_AFTER); PURGE_LEDGER then deletes expired rows.
--
-- Error codes: -20601..-20699 (docs/backend-api.md).

-- One row per deleted account. Holds no name or phone: only the internal ID,
-- the pseudonym used in the ledger, and the harvest IDs that link to the
-- ledger rows still waiting to be purged.
create table hl_erasures (
  erasure_id      number generated by default on null as identity,
  farmer_id       number          not null,  -- the deleted HL_FARMERS.FARMER_ID
  pseudonym       varchar2(40)    not null,  -- written to new ledger rows
  harvest_ids     clob,                      -- JSON array; links to HL_AGREEMENTS.HARVEST_ID
  ledger_rows     number          not null,  -- ledger rows naming the farmer at deletion
  last_ledger_at  timestamp,                 -- newest of those rows
  purge_after     timestamp,                 -- last_ledger_at + 16 days; null when no rows
  purged_at       timestamp,                 -- set by PURGE_LEDGER (at once when no rows)
  requested_by    varchar2(255)   not null,
  requested_at    timestamp       default systimestamp not null,
  constraint hl_erasures_pk primary key (erasure_id),
  constraint hl_erasures_ids_ck check (harvest_ids is json)
);

create or replace package hl_farmer_api as

  -- Days HL_AGREEMENTS keeps a row before it may be deleted (NO DELETE UNTIL)
  c_ledger_retention_days constant pls_integer := 16;

  -- Records that the farmer agreed to a consent notice (default: the latest
  -- published one), stamping the version and time on HL_FARMERS
  procedure record_consent (
    p_farmer_id       in number,
    p_consent_version in varchar2 default null);

  -- Everything held about the farmer, as one JSON document: profile, consent
  -- (with the notice text), logins, harvests, matches, allocations and
  -- agreement ledger rows
  function export_data (p_farmer_id in number) return clob;

  -- Deletes the farmer and everything linked to them except agreement ledger
  -- history (see the header of db/13_farmer_api.sql), logs it in HL_ERASURES
  -- and re-matches the freed demand. Commits nothing; on error, undoes its
  -- own changes.
  procedure delete_account (p_farmer_id in number);

  -- Operations only. Deletes every HL_AGREEMENTS row older than the newest
  -- row of each erased farmer whose PURGE_AFTER has passed. The ledger can only
  -- be trimmed from the oldest row forward, so this also removes other parties'
  -- rows of the same age. Returns the number of rows deleted. Commits nothing.
  function purge_ledger return number;

end hl_farmer_api;
/

create or replace package body hl_farmer_api as

  -- The farmer themselves, or operations. Scripts run outside APEX as the
  -- schema owner with no mapped login are trusted.
  procedure check_access (p_farmer_id in number) is
    l_role hl_app_users.role%type := hl_auth.role;
  begin
    if l_role = 'OPS'
       or (l_role = 'FARMER' and hl_auth.farmer_id = p_farmer_id)
       or (l_role is null and sys_context('APEX$SESSION', 'APP_USER') is null) then
      return;
    end if;
    raise_application_error(-20603, 'You can only see or delete your own farmer account');
  end check_access;

  procedure check_exists (p_farmer_id in number) is
    l_found number;
  begin
    select count(*) into l_found from hl_farmers where farmer_id = p_farmer_id;
    if l_found = 0 then
      raise_application_error(-20601, 'Farmer ' || p_farmer_id || ' does not exist');
    end if;
  end check_exists;

  procedure record_consent (
    p_farmer_id       in number,
    p_consent_version in varchar2 default null
  ) is
    l_found number;
  begin
    check_access(p_farmer_id);
    check_exists(p_farmer_id);
    if p_consent_version is not null then
      select count(*) into l_found from hl_consent_texts where consent_version = p_consent_version;
      if l_found = 0 then
        raise_application_error(-20602, 'Consent notice ' || p_consent_version || ' does not exist');
      end if;
    end if;

    -- HL_FARMERS_CONSENT fills in the latest version when none is given
    update hl_farmers
       set consent_given   = 'Y',
           consent_version = p_consent_version,
           consent_at      = systimestamp
     where farmer_id = p_farmer_id;
  end record_consent;

  function export_data (p_farmer_id in number) return clob is
    l_json clob;
  begin
    check_access(p_farmer_id);
    check_exists(p_farmer_id);

    select json_object(
             'exported_at' value systimestamp,
             'farmer' value json_object(
               'farmer_id'      value f.farmer_id,
               'full_name'      value f.full_name,
               'phone'          value f.phone,
               'county'         value f.county,
               'location_name'  value f.location_name,
               'latitude'       value f.latitude,
               'longitude'      value f.longitude,
               'cooperative'    value f.cooperative,
               'has_smartphone' value f.has_smartphone,
               'created_at'     value f.created_at),
             'consent' value json_object(
               'given'        value f.consent_given,
               'version'      value f.consent_version,
               'given_at'     value f.consent_at,
               'notice_text'  value t.consent_text),
             'logins' value nvl((
               select json_arrayagg(json_object(
                        'user_name' value u.user_name,
                        'role'      value u.role,
                        'created_at' value u.created_at)
                      order by u.user_name returning clob)
                 from hl_app_users u
                where u.role = 'FARMER' and u.party_name = f.full_name), to_clob('[]')) format json,
             'harvests' value nvl((
               select json_arrayagg(json_object(
                        'harvest_id'      value h.harvest_id,
                        'crop'            value c.crop_name,
                        'grade'           value h.grade,
                        'expected_qty_kg' value h.expected_qty_kg,
                        'harvest_from'    value h.harvest_from,
                        'harvest_to'      value h.harvest_to,
                        'status'          value h.status,
                        'notes'           value h.notes,
                        'created_at'      value h.created_at)
                      order by h.harvest_from, h.harvest_id returning clob)
                 from hl_harvests h
                 join hl_crops c on c.crop_id = h.crop_id
                where h.farmer_id = f.farmer_id), to_clob('[]')) format json,
             'matches' value nvl((
               select json_arrayagg(json_object(
                        'match_id'     value m.match_id,
                        'demand_id'    value m.demand_id,
                        'harvest_id'   value m.harvest_id,
                        'buyer'        value b.buyer_name,
                        'crop'         value c.crop_name,
                        'allocated_kg' value m.allocated_kg,
                        'price_per_kg' value d.price_per_kg,
                        'need_by_date' value d.need_by_date,
                        'distance_km'  value m.distance_km,
                        'status'       value m.status,
                        'reason'       value m.match_reason,
                        'created_at'   value m.created_at)
                      order by m.match_id returning clob)
                 from hl_matches m
                 join hl_harvests h on h.harvest_id = m.harvest_id
                 join hl_demands d on d.demand_id = m.demand_id
                 join hl_buyers b on b.buyer_id = d.buyer_id
                 join hl_crops c on c.crop_id = d.crop_id
                where h.farmer_id = f.farmer_id), to_clob('[]')) format json,
             'allocations' value nvl((
               select json_arrayagg(json_object(
                        'allocation_id' value a.allocation_id,
                        'harvest_id'    value a.harvest_id,
                        'outlet'        value b.buyer_name,
                        'alloc_kg'      value a.alloc_kg,
                        'created_at'    value a.created_at)
                      order by a.allocation_id returning clob)
                 from hl_allocations a
                 join hl_harvests h on h.harvest_id = a.harvest_id
                 join hl_buyers b on b.buyer_id = a.buyer_id
                where h.farmer_id = f.farmer_id), to_clob('[]')) format json,
             'agreement_ledger' value nvl((
               select json_arrayagg(json_object(
                        'chain_seq'    value l.chain_seq,
                        'match_id'     value l.match_id,
                        'event'        value l.event,
                        'farmer_name'  value l.farmer_name,
                        'farmer_phone' value l.farmer_phone,
                        'buyer'        value l.buyer_name,
                        'crop'         value l.crop_name,
                        'grade'        value l.grade,
                        'quantity_kg'  value l.quantity_kg,
                        'price_per_kg' value l.price_per_kg,
                        'value_kes'    value l.value_kes,
                        'recorded_by'  value l.recorded_by,
                        'recorded_at'  value l.recorded_at,
                        'row_hash'     value l.row_hash)
                      order by l.recorded_at, l.chain_seq returning clob)
                 from hl_agreements_v l
                where l.harvest_id in (select h.harvest_id from hl_harvests h
                                        where h.farmer_id = f.farmer_id)), to_clob('[]')) format json,
             'retention' value
               'Agreement ledger rows cannot be changed and are kept for at least '
               || c_ledger_retention_days || ' days after they are written, also after the '
               || 'account is deleted. Everything else is removed when the account is deleted.'
             returning clob)
      into l_json
      from hl_farmers f
      left join hl_consent_texts t on t.consent_version = f.consent_version
     where f.farmer_id = p_farmer_id;
    return l_json;
  end export_data;

  procedure delete_account (p_farmer_id in number) is
    l_name        hl_farmers.full_name%type;
    l_erasure_id  hl_erasures.erasure_id%type;
    l_pseudonym   hl_erasures.pseudonym%type;
    l_harvest_ids hl_erasures.harvest_ids%type;
    l_rows        number;
    l_last_at     timestamp;
    l_demands     sys.odcinumberlist;
  begin
    savepoint hl_delete_account;
    check_access(p_farmer_id);
    begin
      select full_name into l_name from hl_farmers where farmer_id = p_farmer_id for update;
    exception
      when no_data_found then
        raise_application_error(-20601, 'Farmer ' || p_farmer_id || ' does not exist');
    end;

    hl_match_pkg.g_auto_match := false;

    -- What the ledger holds about this farmer, before anything changes
    select json_arrayagg(harvest_id order by harvest_id returning clob)
      into l_harvest_ids
      from hl_harvests
     where farmer_id = p_farmer_id;
    select count(*), max(recorded_at)
      into l_rows, l_last_at
      from hl_agreements
     where harvest_id in (select harvest_id from hl_harvests where farmer_id = p_farmer_id);
    select distinct m.demand_id
      bulk collect into l_demands
      from hl_matches m
      join hl_harvests h on h.harvest_id = m.harvest_id
     where h.farmer_id = p_farmer_id;

    insert into hl_erasures (farmer_id, pseudonym, harvest_ids, ledger_rows,
                             last_ledger_at, purge_after, purged_at, requested_by)
    values (p_farmer_id, 'Erased farmer', nvl(l_harvest_ids, to_clob('[]')), l_rows, l_last_at,
            l_last_at + numtodsinterval(c_ledger_retention_days, 'DAY'),
            case when l_rows = 0 then systimestamp end, hl_auth.app_user)
    returning erasure_id into l_erasure_id;
    l_pseudonym := 'Erased farmer #' || l_erasure_id;
    update hl_erasures set pseudonym = l_pseudonym where erasure_id = l_erasure_id;

    -- Pseudonymise first: the ledger trigger copies name and phone from here
    update hl_farmers
       set full_name = l_pseudonym,
           phone     = substr('ERASED-' || p_farmer_id, 1, 20)
     where farmer_id = p_farmer_id;

    -- End confirmed agreements, so the ledger shows them as REJECTED
    for m in (select m.match_id
                from hl_matches m
                join hl_harvests h on h.harvest_id = m.harvest_id
               where h.farmer_id = p_farmer_id
                 and m.status = 'ACCEPTED') loop
      hl_match_pkg.reject_match(m.match_id);
    end loop;

    -- Harvests cascade to matches (incl. delivered), allocations and route stops
    delete from hl_harvests where farmer_id = p_farmer_id;
    delete from hl_app_users where role = 'FARMER' and party_name = l_name;
    delete from hl_farmers where farmer_id = p_farmer_id;

    -- Re-plan the routes the farmer was on. A dispatched route is not
    -- re-planned, so take the name out of its stop list instead.
    for i in 1 .. l_demands.count loop
      hl_match_pkg.plan_route(l_demands(i));
      hl_match_pkg.refresh_statuses(l_demands(i));
    end loop;
    update hl_routes
       set route_sequence = replace(route_sequence, l_name, l_pseudonym)
     where demand_id in (select column_value from table(l_demands))
       and instr(route_sequence, l_name) > 0;

    -- The freed demand goes to other farmers
    hl_match_pkg.rematch_all;
    hl_match_pkg.g_auto_match := true;
  exception
    when others then
      hl_match_pkg.g_auto_match := true;
      rollback to hl_delete_account;
      raise;
  end delete_account;

  function purge_ledger return number is
    l_before  timestamp;
    l_deleted number := 0;
  begin
    if not hl_auth.is_ops
       and not (hl_auth.role is null and sys_context('APEX$SESSION', 'APP_USER') is null) then
      raise_application_error(-20605, 'Only operations can purge the agreement ledger');
    end if;

    select max(last_ledger_at)
      into l_before
      from hl_erasures
     where purged_at is null
       and purge_after <= systimestamp;
    if l_before is null then
      return 0;
    end if;

    -- Rows strictly before the cutoff are deleted, so step just past the newest
    dbms_blockchain_table.delete_expired_rows(
      schema_name            => user,
      table_name             => 'HL_AGREEMENTS',
      before_timestamp       => l_before + numtodsinterval(1, 'SECOND'),
      number_of_rows_deleted => l_deleted);

    update hl_erasures e
       set e.purged_at = systimestamp
     where e.purged_at is null
       and e.last_ledger_at <= l_before
       and not exists (
             select 1 from hl_agreements a
              where a.harvest_id in (select j.id
                                       from json_table(e.harvest_ids, '$[*]'
                                              columns (id number path '$')) j)
                and a.farmer_name <> e.pseudonym);
    return l_deleted;
  end purge_ledger;

end hl_farmer_api;
/

-- The farmer's own data, for a "My data" page (download as JSON)
create or replace view hl_my_data_v as
select hl_auth.farmer_id                          as farmer_id,
       hl_farmer_api.export_data(hl_auth.farmer_id) as data_json
  from dual
 where hl_auth.farmer_id is not null;
